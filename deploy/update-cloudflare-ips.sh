#!/bin/sh
# Writes /etc/nginx/cloudflare-ips.conf (set_real_ip_from lines) from Cloudflare's published address ranges.
# Run as root, then `nginx -t && nginx -s reload`. Put it in cron / a systemd timer (weekly).
set -eu
OUT="${1:-/etc/nginx/cloudflare-ips.conf}"
TMP="$(mktemp)"
{
  echo "# generated by deploy/update-cloudflare-ips.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  for kind in ips-v4 ips-v6; do
    curl -fsS --max-time 20 "https://www.cloudflare.com/$kind" | while read -r range; do
      [ -n "$range" ] && echo "set_real_ip_from $range;"
    done
  done
} > "$TMP"
# a fetch that returned nothing must not wipe a good file
[ "$(grep -c '^set_real_ip_from' "$TMP")" -ge 10 ] || { echo "too few ranges fetched; keeping the old file" >&2; rm -f "$TMP"; exit 1; }
install -m 644 "$TMP" "$OUT"
rm -f "$TMP"
echo "wrote $OUT ($(grep -c '^set_real_ip_from' "$OUT") ranges)"
